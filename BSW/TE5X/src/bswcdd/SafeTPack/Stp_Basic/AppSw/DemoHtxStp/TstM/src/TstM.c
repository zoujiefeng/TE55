/*******************************************************************************
 *
 * \function      : void TstM_Init(void)
 *
 * \description   : This function initialises Test Manager Module
 *
 *******************************************************************************
 *
 * \param[in]     : None
 *
 * \param[out]    : None
 *
 * \param[in,out] : None
 *
 * \return        : None
 *
 *******************************************************************************
 *
 * \service id:   : 0x01
 *
 * \sync          : Synchronous
 *
 * \reentrancy    : Non-reentrant
 *
 * \pre           :
 * \post          :
 * \attention     : Only the Master Core shall call this function.
 * \traceability  :
 *
 ******************************************************************************/
void TstM_Init(void)
{
    Std_ReturnType Result;
    uint8 CoreId;

    Result = E_NOT_OK;

    /* Get Core Id */
    CoreId = (uint8)Mcal_GetCpuIndex();

    /* Check for Master Core */
    if(CoreId == HTXTESTHND_MASTER_CORE_ID)
    {
        /* Initialise Test Seed */
        TstM_TstSeed = 0U;

        /* Initialise Run-time Test Data */
        TstM_InvalidateRunTimeTestData();

        /* Initialise Test Handler */
        Result = HtxTestHnd_Init();
    }

    /* Check for error */
    if (Result != E_OK)
    {
        /* Report error */
        AppCbk_ErrorHandler(APPCBK_TSTM_INIT_FAIL);
    }

} /* End of TstM_Init() */

