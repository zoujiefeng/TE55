boolean TstM_bProgFlowStartFlag = FALSE;
boolean TstM_bGetProgFlowStartFlag(void)
{
   return TstM_bProgFlowStartFlag;
}

uint32 TstM_GetConsolidatedSignature(void)
{
    uint32 ConsolidatedSignature;
    uint32 u32LocAppSignature01 = 0;
    
    #if(HTXTESTHND_RUNTIME_TEST_GROUPS > 0U)
    uint8 Index;
    uint8 CoreId;
    #endif
    boolean bLocBswReady = FALSE;

    ConsolidatedSignature = 0U;

    #if(HTXTESTHND_RUNTIME_TEST_GROUPS > 0U)


    /* Consolidate signature across all the cores */
    for (CoreId = 0U; CoreId < MCAL_NO_OF_CORES; CoreId++)
    {
        /* Loop through each run-time test group */
        for(Index = 0U; Index < HTXTESTHND_RUNTIME_TEST_GROUPS; Index++)
        {
            /* Consolidate signature if CoreId matches */
            if(CoreId == HtxTestHnd_kRunTimeTestGrpCore[Index])
            {
                ConsolidatedSignature = CRC32(ConsolidatedSignature, TstM_RunTimeTestGroupSignatures[Index]);
            }
        }
    }
    #endif /* #if(HTXTESTHND_RUNTIME_TEST_GROUPS > 0U) */
    
    u32LocAppSignature01 = BSW_u32GetProgFlowSign01();
    bLocBswReady = BSW_bGetBswReadySts();
    if(TRUE == bLocBswReady)
    {
       TstM_bProgFlowStartFlag = TRUE;
       ConsolidatedSignature = CRC32(ConsolidatedSignature, u32LocAppSignature01);
    }

    return ConsolidatedSignature;
} /* End of TstM_GetConsolidatedSignature() */

