/*******************************************************************************
 *
 * \function      : void TstM_VerifyRuntimeTestSig(void)
 *
 * \description   : This function verifies the Signature of the runtime tests
 *
 *******************************************************************************
 *
 * \param[in]     : None
 *
 * \param[out]    : None
 *
 * \param[in,out] : None
 *
 * \return        : None
 *
 *******************************************************************************
 *
 * \service id:   :
 *
 * \sync          : Synchronous
 *
 * \reentrancy    : Non-reentrant
 *
 * \pre           :
 * \post          :
 * \attention     :
 * \traceability  :
 *
 ******************************************************************************/
void TstM_VerifyRuntimeTestSig(void)
{
    uint32 lConsolidatedSignature;

    /* Get consolidated signature from Test Manager */
    lConsolidatedSignature = TstM_GetConsolidatedSignature();

    /* Report error if job result is not success/accepted */
    if(lConsolidatedSignature != TstM_ExpectedRuntimeTestGrpSig[TstM_TstSeed])
    {
        AppCbk_ErrorHandler(APPCBK_SWDGM_SERVICE_FAIL);
    }

    /* Invalidate Test Data and increment the seed */
    TstM_TstSeed = (TstM_TstSeed + 1) % TSTM_TOTAL_TEST_SEED;
    TstM_InvalidateRunTimeTestData();
}
#endif /* End of TstM_VerifyRuntimeTestSig() */

