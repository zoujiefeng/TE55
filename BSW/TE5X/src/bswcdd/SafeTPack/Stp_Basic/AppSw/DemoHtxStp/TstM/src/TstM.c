/*******************************************************************************
 *
 * \function      : void TstM_SwitchToRunPhase(void)
 *
 * \description   : This function switches Test Handler to RUN phase
 *
 *******************************************************************************
 *
 * \param[in]     : None
 *
 * \param[out]    : None
 *
 * \param[in,out] : None
 *
 * \return        : None
 *
 *******************************************************************************
 *
 * \service id:   : 0x03
 *
 * \sync          : Synchronous
 *
 * \reentrancy    : Non-reentrant
 *
 * \pre           :
 * \post          :
 * \attention     : Only the Master Core shall call this function.
 * \traceability  :
 *
 ******************************************************************************/
void TstM_SwitchToRunPhase(void)
{
    Std_ReturnType Result;
    Smu_CoreStateType lSmuState;
    uint8 CoreId;

    Result = E_NOT_OK;

    /* Get Core Id */
    CoreId = (uint8)Mcal_GetCpuIndex();

    /* Check for Master Core */
    if(CoreId == HTXTESTHND_MASTER_CORE_ID)
    {
        /* Initialise SMU driver */
        Result = Smu_Init(&Smu_Config);
        
        /* Check for error */
        if(Result == E_OK)
        {
            lSmuState = Smu_GetSmuState();

            /* Proceed further for valid states of SMU */
            if(lSmuState != SMU_UNDEFINED_STATE)
            {
                /* Note: SMU state machine is not affected by appl/sys reset */
                if(lSmuState != SMU_RUN_STATE)
                {
                    /* Setup FSP pin */
                    Result = Smu_SetupErrorPin();

                    if(Result == E_OK)
                    {
                        /* Release FSP */
                        Result = Smu_ReleaseFSP();
    
                        /* Check for error */
                        if(Result == E_OK)
                        {
                            /* Move SMU to RUN state */
                            Result = Smu_ActivateRunState(SMU_RUN_COMMAND);
                        }
                    }
                }

                /* Check for error */
                if(Result == E_OK)
                {
                    /* Lock the SMU configuration registers */
                    Result = Smu_LockConfigRegs();

                    /* Check for error */
                    if(Result == E_OK)
                    {
                        /* Switch Test Handler to RUN Phase */
                        Result = HtxTestHnd_SwitchToRunPhase();
                    }
                }
                
                SRC_SMU0.U = ((uint32)((uint32)1U << 10) | (uint32)((uint32)0 << 11) | (uint32)250);
            }
            else
            {
                Result = E_NOT_OK;
            }
        }
    }

    /* Check for error */
    if(Result != E_OK)
    {
        /* Report error */
        AppCbk_ErrorHandler(APPCBK_TSTM_SWITCH_TO_RUN_FAIL);
    }

} /* End of TstM_SwitchToRunPhase() */

