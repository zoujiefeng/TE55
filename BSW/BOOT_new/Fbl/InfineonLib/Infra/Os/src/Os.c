/*********************************************************************************************************************
* Function Name:     Os_Start
* Return Value:      None
* Parameters List:   None
* Description:       Initialize Os counters.
*********************************************************************************************************************/
void Os_Start (void)
{
    /* Init Os timer */
    OsPort_InitOsTimerResource();
    CurrTickValue = GET_SYSTEM_TIMER();	/* PRQA S 0303 */ /* Read the value at Register */
    PrevTickValue = CurrTickValue;
    TickValueSum = 0;
}

/*********************************************************************************************************************
* Function Name:     Os_MainFunction
* Return Value:      None
* Parameters List:   None
* Description:       Os main function.
*********************************************************************************************************************/
void Os_MainFunction(void)
{
    while(1)
    {
        CurrTickValue = GET_SYSTEM_TIMER();	/* PRQA S 0303 */ /* Read the value at Register */
        /* Manage the reset of system counter */
        if(CurrTickValue > PrevTickValue)
        {
            TickValueSum = (uint32)(CurrTickValue - PrevTickValue);
        }
        else
        {
            TickValueSum = (uint32)(SYSTEM_TIMER_MAX_VALUE - PrevTickValue + CurrTickValue);
        }

        if(TickValueSum >= (uint32)OS_TICK_TH)  /* PRQA S 1840 */
        {
            TickValueSum = 0;
            PrevTickValue = CurrTickValue;

            /* Call Os tick service */
            Os_SchTickService();
        }
        /* Call Os main scheduler */
        Os_Scheduler();
    }
}
